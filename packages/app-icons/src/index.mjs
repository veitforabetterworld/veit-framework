/**
 * Every app icon of a host from ONE logo SVG (branding/logo.svg): favicon (SVG + ICO), PWA any + maskable,
 * apple-touch-icon, Android adaptive launcher (foreground, background, monochrome), legacy launcher, splash,
 * notification icon and Play Store icon.
 *
 * The source is an ordinary square SVG. An element with id="background" (optional) is the backdrop; everything else
 * is the mark. Variants come from CSS on the root (hide the backdrop, or show only it) and from measuring the
 * rendered mark: no assumptions about the SVG's structure, no colour replacements.
 *
 * - full: the logo as drawn (with backdrop).
 * - mark: the logo without backdrop, cropped to what is drawn.
 * - tile: an opaque square: `full` when the logo has a backdrop, else the mark on `background`.
 * - maskable / adaptive: backdrop layer plus the mark inside the safe circle (PWA: radius 40 %, Android: 33 of 108 dp).
 * - monochrome: white, from the mark's alpha (`alpha`) or with dark parts cut out (`luminance`).
 */
import fs from 'node:fs';
import path from 'node:path';
import { Resvg } from '@resvg/resvg-js';
import { encodeIco, encodePng } from './png.mjs';

/** Icons for the web manifest (vite-plugin-pwa `manifest.icons` or a static manifest), as generated below. */
export const webManifestIcons = [
  { src: '/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
  { src: '/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
  { src: '/icon-192-maskable.png', sizes: '192x192', type: 'image/png', purpose: 'maskable' },
  { src: '/icon-512-maskable.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
];

const DENSITIES = { mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 };
/** Analysis resolution for measuring the mark. */
const MEASURE = 1024;
const PWA_SAFE_RADIUS = 0.4;
const ANDROID_SAFE_RADIUS = 33 / 108;

const ADAPTIVE_ICON_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by @veit/app-icons from branding/logo.svg. Do not edit. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@mipmap/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
    <monochrome android:drawable="@mipmap/ic_launcher_monochrome" />
</adaptive-icon>
`;

