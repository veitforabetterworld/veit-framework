#!/usr/bin/env node
/**
 * Writes the service worker for Web Push into the host's public folder (generated, not versioned), like
 * `veit-app-icons` writes the icons:
 *   veit-web-push-sw --out public [--api /api/v1] [--icon /icon-192.png] [--badge /icon-192.png] [--file sw.js]
 *
 * The worker shows the payloads of '@veit/web-push' (title, body, url, tag, icon, badge, requireInteraction,
 * timestamp, data), opens or focuses the app on a click (an open window gets a message for routing inside the
 * single-page app, see useVeitWebPushOpen) and registers a renewed subscription under {api}/me/push/subscriptions.
 * It has no fetch handler: requests go to the network as without it. In an Android TWA, Chrome delegates the
 * notifications to the app (Bubblewrap's DelegationService).
 */
import fs from 'node:fs';
import path from 'node:path';

function arg(name, fallback) {
  const i = process.argv.indexOf(`--${name}`);
  return i > 0 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
}

const out = arg('out');
if (!out) {
  console.error('veit-web-push-sw: --out <dir> fehlt');
  process.exit(1);
}
const config = {
  api: arg('api', '/v1').replace(/\/$/, ''),
  icon: arg('icon', '/icon-192.png'),
  badge: arg('badge', '/icon-192.png'),
};

const source = `/* Generated by @veit/react-web-push (veit-web-push-sw). Do not edit. */
const CONFIG = ${JSON.stringify(config)};

self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', (event) => event.waitUntil(self.clients.claim()));

self.addEventListener('push', (event) => {
  let data = {};
  try {
    data = event.data ? event.data.json() : {};
  } catch {
    data = { title: event.data ? event.data.text() : '' };
  }
  const title = data.title || self.location.hostname;
  event.waitUntil(
    self.registration.showNotification(title, {
      body: data.body || '',
      icon: data.icon || CONFIG.icon,
      badge: data.badge || CONFIG.badge,
      tag: data.tag,
      renotify: Boolean(data.tag),
      requireInteraction: Boolean(data.requireInteraction),
      timestamp: typeof data.timestamp === 'number' ? data.timestamp : Date.now(),
      data: { ...(data.data || {}), url: data.url || '/' },
    }),
  );
});

self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  const target = new URL((event.notification.data && event.notification.data.url) || '/', self.location.origin).href;
  event.waitUntil(
    (async () => {
      const windows = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
      const open = windows.find((client) => new URL(client.url).origin === self.location.origin);
      if (open) {
        await open.focus();
        open.postMessage({ type: 'veit-web-push-open', url: target });
        return;
      }
      await self.clients.openWindow(target);
    })(),
  );
});

self.addEventListener('pushsubscriptionchange', (event) => {
  const options = event.oldSubscription && event.oldSubscription.options;
  if (!options) return;
  event.waitUntil(
    (async () => {
      const subscription = await self.registration.pushManager.subscribe(options);
      await fetch(CONFIG.api + '/me/push/subscriptions', {
        method: 'POST',
        credentials: 'include',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(subscription.toJSON()),
      });
    })(),
  );
});
`;

const file = path.join(out, arg('file', 'sw.js'));
fs.mkdirSync(out, { recursive: true });
const before = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
if (before !== source) {
  fs.writeFileSync(file, source, 'utf8');
  console.log(`veit-web-push-sw: ${file}`);
}
