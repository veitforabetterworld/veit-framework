/**
 * Config (branding/app-icons.json), paths relative to that file:
 * {
 *   "source": "logo.svg",
 *   "background": "#DAA520",            // backdrop for maskable/adaptive/tile when the logo has no id="background"
 *   "monochrome": "alpha" | "luminance" | { "themed": …, "notification": … },  // default alpha
 *   "safeZoneFill": 0.9,                // how much of the safe circle the mark fills
 *   "web": { "out": "../apps/web/public", "icon": "full" | "mark" },
 *   "android": { "res": "../android-twa/app/src/main/res", "storeIcon": "../android-twa/store_icon.png", "splash": "full" | "mark" }
 * }
 */
export function readConfig(configPath) {
  const abs = path.resolve(configPath);
  const config = JSON.parse(fs.readFileSync(abs, 'utf8'));
  const dir = path.dirname(abs);
  const at = (p) => (p ? path.resolve(dir, p) : undefined);
  if (!config.source) throw new Error(`app-icons: "source" missing in ${configPath}`);
  return {
    source: at(config.source),
    background: config.background,
    monochrome: {
      themed: (typeof config.monochrome === 'object' ? config.monochrome?.themed : config.monochrome) ?? 'alpha',
      notification: (typeof config.monochrome === 'object' ? config.monochrome?.notification : config.monochrome) ?? 'alpha',
    },
    fill: config.safeZoneFill ?? 0.9,
    web: config.web ? { out: at(config.web.out), icon: config.web.icon ?? 'full' } : null,
    android: config.android
      ? { res: at(config.android.res), storeIcon: at(config.android.storeIcon), splash: config.android.splash ?? 'full' }
      : null,
  };
}

function writeFile(file, data, written) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, data);
  written.push(file);
}

/** The vector form of a variant at size 512 for an SVG file: `mark` stays vector via a cropped root viewBox. */
function svgFile(source, kind) {
  if (kind === 'mark') {
    const [x, y, w, h] = source.mark.box;
    const side = Math.max(w, h);
    return `${rewrite({ svg: source.markSvg }, { viewBox: [x - (side - w) / 2, y - (side - h) / 2, side, side] })}\n`;
  }
  if (source.hasBackground) return `${rewrite(source)}\n`;
  return `${variants.tile(source, 512)}\n`;
}

export function generateWeb(source, { out, icon }, { fill }) {
  const written = [];
  const variant = icon === 'mark' ? (s, n) => variants.mark(s, n) : (s, n) => variants.tile(s, n);
  writeFile(path.join(out, 'app-mark.svg'), svgFile(source, 'mark'), written);
  writeFile(path.join(out, 'app-icon.svg'), svgFile(source, 'tile'), written);
  writeFile(path.join(out, 'favicon.svg'), svgFile(source, icon === 'mark' ? 'mark' : 'tile'), written);
  writeFile(
    path.join(out, 'favicon.ico'),
    encodeIco([16, 32, 48].map((size) => ({ size, png: renderPng(variant(source, size)) }))),
    written,
  );
  // iOS fills transparency with black and rounds the corners itself: an opaque tile.
  writeFile(path.join(out, 'apple-touch-icon.png'), renderPng(variants.tile(source, 180)), written);
  for (const size of [192, 512]) {
    writeFile(path.join(out, `icon-${size}.png`), renderPng(variant(source, size)), written);
    writeFile(path.join(out, `icon-${size}-maskable.png`), renderPng(variants.maskable(source, size, { fill })), written);
  }
  return written;
}

export function generateAndroid(source, { res, storeIcon, splash }, { fill, monochrome: mode }) {
  const written = [];
  for (const [density, k] of Object.entries(DENSITIES)) {
    const mipmap = path.join(res, `mipmap-${density}`);
    const drawable = path.join(res, `drawable-${density}`);
    // Launchers before Android 8 show this square as it is.
    writeFile(path.join(mipmap, 'ic_launcher.png'), renderPng(variants.tile(source, Math.round(48 * k))), written);
    const adaptive = Math.round(108 * k);
    const foreground = variants.adaptiveForeground(source, adaptive, { fill });
    writeFile(path.join(mipmap, 'ic_launcher_foreground.png'), renderPng(foreground), written);
    writeFile(path.join(mipmap, 'ic_launcher_background.png'), renderPng(variants.adaptiveBackground(source, adaptive)), written);
    writeFile(path.join(mipmap, 'ic_launcher_monochrome.png'), renderMonochrome(foreground, mode.themed), written);
    const splashSize = Math.round(300 * k);
    const splashSvg = splash === 'mark' ? variants.mark(source, splashSize) : variants.tile(source, splashSize);
    writeFile(path.join(drawable, 'splash.png'), renderPng(splashSvg), written);
    // Status bar icon: 24 dp, content within 22 dp.
    const notification = variants.mark(source, Math.round(24 * k), { padding: 1 / 24 });
    writeFile(path.join(drawable, 'ic_notification_icon.png'), renderMonochrome(notification, mode.notification), written);
  }
  writeFile(path.join(res, 'mipmap-anydpi-v26', 'ic_launcher.xml'), ADAPTIVE_ICON_XML, written);
  // Play Store: 512 × 512, opaque, full bleed (the store rounds it).
  if (storeIcon) writeFile(storeIcon, renderPng(variants.tile(source, 512)), written);
  return written;
}

/** Generates everything the config names; returns the written files. */
export function generateAppIcons(configPath, { only } = {}) {
  const config = readConfig(configPath);
  const source = loadLogo(fs.readFileSync(config.source, 'utf8'), { background: config.background });
  const written = [];
  if (config.web && (!only || only === 'web')) written.push(...generateWeb(source, config.web, config));
  if (config.android && (!only || only === 'android')) written.push(...generateAndroid(source, config.android, config));
  return written;
}
