export type VeitAuthLocale = keyof typeof veitAuthMessages;

/** t() over the built-in texts; overrides win, unknown keys come back unchanged. */
export function veitAuthT(locale: VeitAuthLocale, overrides: Record<string, string> = {}): (key: string) => string {
  const table: Record<string, string> = veitAuthMessages[locale];
  return (key) => overrides[key] ?? table[key] ?? key;
}

/** The text for an error thrown by the REST clients (VeitApiError carries the server's code). */
export function veitAuthErrorText(error: unknown, t: (key: string) => string): string {
  const code =
    typeof error === 'object' && error !== null && 'code' in error && typeof (error as { code: unknown }).code === 'string'
      ? (error as { code: string }).code
      : 'internal';
  const text = t(code);
  return text === code ? t('internal') : text;
}
