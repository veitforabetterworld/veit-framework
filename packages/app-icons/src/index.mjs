function parseRoot(svg) {
  const match = svg.match(/<svg\b[^>]*>/i);
  if (!match) throw new Error('app-icons: no <svg> root in the logo');
  const tag = match[0];
  const attr = (name) => tag.match(new RegExp(`\\s${name}\\s*=\\s*["']([^"']*)["']`, 'i'))?.[1];
  let viewBox = attr('viewBox')
    ?.trim()
    .split(/[\s,]+/)
    .map(Number);
  if (!viewBox || viewBox.length !== 4 || viewBox.some((n) => !Number.isFinite(n))) {
    const w = Number.parseFloat(attr('width') ?? '');
    const h = Number.parseFloat(attr('height') ?? '');
    if (!(w > 0 && h > 0)) throw new Error('app-icons: the logo needs a viewBox or width and height');
    viewBox = [0, 0, w, h];
  }
  return { tag, start: match.index, end: match.index + tag.length, viewBox };
}

/** The source with another viewBox and extra CSS; width/height are left to whoever embeds it. */
function rewrite(source, { viewBox, css } = {}) {
  const root = parseRoot(source.svg);
  const vb = viewBox ?? root.viewBox;
  const attrs = root.tag
    .replace(/^<svg\b/i, '')
    .replace(/\/?>$/, '')
    .replace(/\s(width|height|viewBox|preserveAspectRatio)\s*=\s*("[^"]*"|'[^']*')/gi, '');
  const xmlns = /\sxmlns\s*=/.test(attrs) ? '' : ' xmlns="http://www.w3.org/2000/svg"';
  const tag = `<svg${xmlns}${attrs} viewBox="${vb.map((n) => round(n)).join(' ')}">`;
  const style = css ? `<style>${css}</style>` : '';
  return `${tag}${style}${source.svg.slice(root.end)}`.replace(/^\s+/, '');
}

function round(n) {
  return Math.round(n * 1000) / 1000;
}

const HIDE_BACKGROUND = '#background{display:none}';
const ONLY_BACKGROUND = 'svg *{visibility:hidden} #background,#background *{visibility:visible}';

export function loadLogo(svgText, { background } = {}) {
  const root = parseRoot(svgText);
  const hasBackground = /\sid\s*=\s*["']background["']/.test(svgText);
  const source = { svg: svgText, viewBox: root.viewBox, hasBackground, background };
  source.markSvg = hasBackground ? rewrite(source, { css: HIDE_BACKGROUND }) : rewrite(source);
  source.backgroundSvg = hasBackground ? rewrite(source, { css: ONLY_BACKGROUND }) : null;
  source.mark = measureMark(source);
  if (!hasBackground && !background) {
    throw new Error('app-icons: the logo has no id="background"; set "background" (a colour) in the config');
  }
  return source;
}

/** Bounding box of what the mark draws and its largest distance from the box centre, in viewBox units. */
function measureMark(source) {
  const [vx, vy, vw] = source.viewBox;
  const img = new Resvg(rewrite({ svg: source.markSvg }), { fitTo: { mode: 'width', value: MEASURE } }).render();
  const { width, height, pixels } = img;
  let x0 = width;
  let y0 = height;
  let x1 = -1;
  let y1 = -1;
  for (let y = 0; y < height; y += 1) {
    for (let x = 0; x < width; x += 1) {
      if (pixels[(y * width + x) * 4 + 3] > 2) {
        if (x < x0) x0 = x;
        if (x > x1) x1 = x;
        if (y < y0) y0 = y;
        if (y > y1) y1 = y;
      }
    }
  }
  if (x1 < 0) throw new Error('app-icons: the mark is empty (everything is id="background"?)');
  const cx = (x0 + x1 + 1) / 2;
  const cy = (y0 + y1 + 1) / 2;
  let r2 = 0;
  for (let y = y0; y <= y1; y += 1) {
    for (let x = x0; x <= x1; x += 1) {
      if (pixels[(y * width + x) * 4 + 3] > 2) {
        // farthest corner of the pixel
        const dx = Math.max(Math.abs(x - cx), Math.abs(x + 1 - cx));
        const dy = Math.max(Math.abs(y - cy), Math.abs(y + 1 - cy));
        r2 = Math.max(r2, dx * dx + dy * dy);
      }
    }
  }
  const k = vw / width;
  const pad = 1; // one analysis pixel against clipped anti-aliasing
  return {
    box: [vx + (x0 - pad) * k, vy + (y0 - pad) * k, (x1 - x0 + 1 + 2 * pad) * k, (y1 - y0 + 1 + 2 * pad) * k],
    radius: (Math.sqrt(r2) + pad) * k,
  };
}

// ---------------------------------------------------------------------------------------------------------------
// Composition

function dataUri(svg) {
  return `data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}`;
}

function image(svg, [x, y, w, h], fit = 'meet') {
  return `<image x="${round(x)}" y="${round(y)}" width="${round(w)}" height="${round(h)}" preserveAspectRatio="xMidYMid ${fit}" href="${dataUri(svg)}"/>`;
}

function canvas(size, layers) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">${layers.join('')}</svg>`;
}

/** The mark cropped to its box, as an SVG of its own. */
function croppedMark(source) {
  return rewrite({ svg: source.markSvg }, { viewBox: source.mark.box });
}

/** Mark scaled so its box fits a centred square of `inner` (fraction of size). */
function markInSquare(source, size, inner) {
  const [, , bw, bh] = source.mark.box;
  const scale = (size * inner) / Math.max(bw, bh);
  const w = bw * scale;
  const h = bh * scale;
  return image(croppedMark(source), [(size - w) / 2, (size - h) / 2, w, h]);
}

/** Mark scaled so everything it draws lies inside the centred circle of radius `radius` (fraction of size). */
function markInCircle(source, size, radius) {
  const [, , bw, bh] = source.mark.box;
  const scale = (size * radius) / source.mark.radius;
  const w = bw * scale;
  const h = bh * scale;
  return image(croppedMark(source), [(size - w) / 2, (size - h) / 2, w, h]);
}

function backgroundLayer(source, size) {
  if (source.backgroundSvg) return image(source.backgroundSvg, [0, 0, size, size], 'slice');
  return `<rect width="${size}" height="${size}" fill="${source.background}"/>`;
}

export const variants = {
  full: (source, size) => canvas(size, [image(rewrite(source), [0, 0, size, size])]),
  mark: (source, size, { padding = 0 } = {}) => canvas(size, [markInSquare(source, size, 1 - 2 * padding)]),
  tile: (source, size, { padding = 0.15 } = {}) =>
    source.hasBackground ? variants.full(source, size) : canvas(size, [backgroundLayer(source, size), markInSquare(source, size, 1 - 2 * padding)]),
  maskable: (source, size, { fill = 0.9 } = {}) => canvas(size, [backgroundLayer(source, size), markInCircle(source, size, PWA_SAFE_RADIUS * fill)]),
  adaptiveForeground: (source, size, { fill = 0.9 } = {}) => canvas(size, [markInCircle(source, size, ANDROID_SAFE_RADIUS * fill)]),
  adaptiveBackground: (source, size) => canvas(size, [backgroundLayer(source, size)]),
};

function render(svg) {
  return new Resvg(svg).render();
}

function renderPng(svg) {
  return Buffer.from(render(svg).asPng());
}

/**
 * White silhouette. `alpha`: everything the mark draws. `luminance`: dark parts (text, lines) become holes, so a
 * light mark with dark detail keeps its detail. resvg pixels are premultiplied.
 */
export function monochrome(img, mode = 'alpha') {
  const { width, height, pixels } = img;
  const out = Buffer.alloc(width * height * 4);
  for (let i = 0; i < width * height * 4; i += 4) {
    const a = pixels[i + 3];
    let alpha = a;
    if (mode === 'luminance' && a > 0) {
      const lum = (0.2126 * pixels[i] + 0.7152 * pixels[i + 1] + 0.0722 * pixels[i + 2]) / a;
      const t = Math.min(1, Math.max(0, (lum - 0.35) / 0.3));
      alpha = Math.round(a * t * t * (3 - 2 * t));
    }
    out[i] = 255;
    out[i + 1] = 255;
    out[i + 2] = 255;
    out[i + 3] = alpha;
  }
  return encodePng(width, height, out);
}

function renderMonochrome(svg, mode) {
  return monochrome(render(svg), mode);
}

